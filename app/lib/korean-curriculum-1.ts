export type CurriculumSession = {
  semester: CurriculumSemester;
  unit: string;
  totalSessions: number;
  currentSession: number;
  topic: string;
  standardCodes: string[];
  textbookName: string;
  textbookPages: string;
};

function expand(semester: CurriculumSemester, textbookName: string, rows: Row[]): CurriculumSession[] {
  return rows.map(([unit, totalSessions, currentSession, topic, codes, textbookPages]) => ({
    semester, unit, totalSessions, currentSession, topic,
    standardCodes: codes.split(","),
    textbookName, textbookPages,
  }));
}

export const FIRST_GRADE_KOREAN_CURRICULUM: CurriculumSession[] = [
  ...expand("1학기", "미래엔 초등 국어 1-1", S1),
  ...expand("2학기", "미래엔 초등 국어 1-2", S2),
];

export function curriculumUnits(semester: CurriculumSemester): { unit: string; totalSessions: number }[] {
  const seen = new Map<string, number>();
  for (const row of FIRST_GRADE_KOREAN_CURRICULUM) {
    if (row.semester === semester && !seen.has(row.unit)) seen.set(row.unit, row.totalSessions);
  }
  return [...seen.entries()].map(([unit, totalSessions]) => ({ unit, totalSessions }));
}

export function curriculumTopics(semester: CurriculumSemester, unit: string): { topic: string; currentSession: number }[] {
  return FIRST_GRADE_KOREAN_CURRICULUM.filter(row => row.semester === semester && row.unit === unit)
    .map(row => ({ topic: row.topic, currentSession: row.currentSession }));
}

export function findCurriculumSession(semester: string, unit: string, topic: string): CurriculumSession | undefined {
  return FIRST_GRADE_KOREAN_CURRICULUM.find(row => row.semester === semester && row.unit === unit && row.topic === topic);
}

export function formatStandards(codes: string[]): string {
  return codes.map(code => `[2국${code}] ${ACHIEVEMENT_STANDARDS[code] || ""}`).join("\n");
}
