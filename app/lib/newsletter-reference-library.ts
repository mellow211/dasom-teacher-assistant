export function selectNewsletterReferences(input: NewsletterInput): string {
  const patternText = PATTERNS.filter(pattern => pattern.types.includes(input.type)).map(pattern => `- ${pattern.name}: ${pattern.structure.join(" → ")}\n  작성 특징: ${pattern.writingNotes.join(" / ")}`).join("\n");
  return `[공식 공개 사례에서 추출한 ${input.type} 문서 패턴]\n${patternText}\n\n[대전광역시교육청 2026 개인정보보호 지침에서 추출한 작성 규칙]\n${PRIVACY_WRITING_RULES.map(rule => `- ${rule}`).join("\n")}`;
}
